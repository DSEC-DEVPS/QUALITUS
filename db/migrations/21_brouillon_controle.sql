USE QUALITUS;

CREATE TABLE IF NOT EXISTS B_BROUILLON_CONTROLE (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  id_UTILISATEUR INT NOT NULL,
  typeControle VARCHAR(50) NOT NULL,
  fiches JSON NOT NULL,
  UNIQUE KEY uq_brouillon_controle_utilisateur_type (id_UTILISATEUR, typeControle),
  FOREIGN KEY (id_UTILISATEUR) REFERENCES B_UTILISATEUR(id) ON DELETE CASCADE
) ENGINE=InnoDB;
